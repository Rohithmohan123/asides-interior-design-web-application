// Writes frontend/src/app/demo/demo-data.ts from the backend seed data, so the static
// GitHub Pages demo shows exactly the same sample content as a freshly seeded database.
import { writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { categories, projects, IMAGE_LIBRARY } from '../backend/src/seed-data.js';
import { PROJECT_TYPES, BUDGET_RANGES } from '../backend/src/validation.js';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const cats = categories.map((c, i) => ({ id: i + 1, ...c }));
const idOf = Object.fromEntries(cats.map((c) => [c.slug, c.id]));
const stamp = '2026-01-15 10:00:00';
const projs = projects.map((p, i) => ({
  id: i + 1, slug: p.slug, title: p.title, category_id: idOf[p.category], location: p.location, area_sqft: p.area_sqft,
  year: p.year, style: p.style, summary: p.summary, description: p.description, highlights: p.highlights, materials: p.materials,
  cover_image: p.cover_image, gallery: p.gallery, featured: !!p.featured, published: p.published !== 0,
  created_at: stamp, updated_at: stamp
}));
const out = `// GENERATED by tools/generate-demo-data.mjs from backend/src/seed-data.js. Do not edit by hand.
// Fictional sample content used by the static demo build (no backend).
/* eslint-disable */
export const DEMO_CATEGORIES: any[] = ${JSON.stringify(cats)};
export const DEMO_PROJECTS: any[] = ${JSON.stringify(projs)};
export const DEMO_IMAGES: string[] = ${JSON.stringify(IMAGE_LIBRARY)};
export const DEMO_PROJECT_TYPES: string[] = ${JSON.stringify(PROJECT_TYPES)};
export const DEMO_BUDGET_RANGES: string[] = ${JSON.stringify(BUDGET_RANGES)};
`;
writeFileSync(resolve(root, 'frontend/src/app/demo/demo-data.ts'), out);
console.log(`demo data: ${cats.length} categories, ${projs.length} projects, ${IMAGE_LIBRARY.length} library images`);
